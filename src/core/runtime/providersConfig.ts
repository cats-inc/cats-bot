import { mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { writeFileAtomic } from '../store/atomicFile.ts';

/**
 * The private runtime needs a valid `config/providers.yaml`, otherwise it
 * starts in bootstrap mode and answers every session route with 409. The bot
 * writes the smallest selection that enables its one provider as a native
 * CLI target (runtime docs/api.md "Bootstrap Mode" and "Provider Setup").
 */

export interface ProvidersConfigInput {
  provider: string;
  /** Overrides the CLI command; tests point it at the fixture CLI. */
  command?: string;
  /** Extra instance keys, for example `projects_dir` for the fixture. */
  instanceExtras?: Record<string, string>;
}

const GENERATED_MARKER = '# generated by cats-bots; edits are replaced on the next start';

function yamlScalar(value: string): string {
  return JSON.stringify(value);
}

export function renderProvidersConfig(input: ProvidersConfigInput): string {
  const lines = [
    GENERATED_MARKER,
    'version: 1',
    'environments:',
    '  native:',
    '    kind: native',
    'routing:',
    '  providers:',
    `    ${input.provider}:`,
    '      default_target:',
    '        backend: cli',
    '        instance: native',
    'backends:',
    '  cli:',
    '    providers:',
    `      ${input.provider}:`,
    '        instances:',
    '          native:',
    '            environment: native',
    `            command: ${yamlScalar(input.command ?? input.provider)}`,
    '            runner: auto',
  ];
  for (const [key, value] of Object.entries(input.instanceExtras ?? {})) {
    lines.push(`            ${key}: ${yamlScalar(value)}`);
  }
  return `${lines.join('\n')}\n`;
}

export function providersConfigPath(runtimeDir: string): string {
  return join(runtimeDir, 'config', 'providers.yaml');
}

/** Writes the file when it is missing or differs; returns whether it changed. */
export function ensureProvidersConfig(runtimeDir: string, input: ProvidersConfigInput): boolean {
  const path = providersConfigPath(runtimeDir);
  const desired = renderProvidersConfig(input);
  let current: string | null = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    current = null;
  }
  if (current === desired) return false;
  mkdirSync(join(runtimeDir, 'config'), { recursive: true });
  writeFileAtomic(path, desired);
  return true;
}
