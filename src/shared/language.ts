export function translate(
  locale: Locale,
  message: string,
  values: Record<string, unknown> = {},
): string {
  const template = locale === 'zh-TW' ? (zhTW[message] ?? message) : message;
  return template.replace(/\{(\w+)\}/gu, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
