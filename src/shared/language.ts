/** Same display-language choices as Cats Desktop. No renderer or Node imports. */
export type LanguagePreference = 'system' | 'en' | 'zh-TW';
export type Locale = 'en' | 'zh-TW';
export const LANGUAGE_OPTIONS: ReadonlyArray<{ value: LanguagePreference; label: string }> = [
  { value: 'system', label: 'Follow system' },
  { value: 'en', label: 'English' },
  { value: 'zh-TW', label: '繁體中文' },
];
export function isLanguagePreference(value: unknown): value is LanguagePreference {
  return LANGUAGE_OPTIONS.some((option) => option.value === value);
}
export function resolveLocale(preference: LanguagePreference, systemLocale: string): Locale {
  if (preference !== 'system') return preference;
  return /^(?:zh(?:$|-(?:tw|hant|hk|mo)(?:-|$)))/iu.test(systemLocale.replaceAll('_', '-'))
    ? 'zh-TW'
    : 'en';
}
export interface LanguageState {
  preference: LanguagePreference;
  locale: Locale;
}

